// Browser evidence for the actual template/styles/page handlers with mocked cloud/platform APIs.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const http = require('node:http')
const path = require('node:path')
const { execFileSync } = require('node:child_process')
const { chromium } = require('playwright')
const root = path.resolve(__dirname, '..')
const artifacts = process.env.GROWTH_EVIDENCE_DIR || '/tmp/growth-verification'
fs.mkdirSync(artifacts, { recursive: true })
const html = path.join(artifacts, 'growth-preview.html')
execFileSync(process.execPath, [path.join(root, 'scripts/preview-growth.js'), html])

async function main() {
  const server = http.createServer((req, res) => { res.setHeader('Content-Type', 'text/html; charset=utf-8'); res.end(fs.readFileSync(html)) })
  await new Promise(resolve => server.listen(4173, '127.0.0.1', resolve))
  let browser
  const errors = [], verified = []
  try {
    browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
    const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })
    page.on('pageerror', err => errors.push(err.message))
    await page.goto('http://127.0.0.1:4173')
    await page.getByText('小满的成长手记', { exact: true }).waitFor()
    await page.waitForTimeout(100)
    await page.screenshot({ path: path.join(artifacts, 'overview.png') })
    await page.getByRole('button', { name: '体重', exact: true }).click()
    assert.equal(await page.evaluate(() => window.page.data.chart.metric), 'weight')
    await page.getByRole('button', { name: '0–18岁', exact: true }).click()
    assert.equal(await page.evaluate(() => window.page.data.chart.maxX), 216)
    await page.getByRole('button', { name: '身高', exact: true }).click()
    verified.push('metric and age-range switching')
    await page.locator('.timeline-heading').scrollIntoViewIfNeeded()
    await page.screenshot({ path: path.join(artifacts, 'timeline.png') })
    await page.evaluate(() => document.querySelector('.growth-scroll').scrollTop = 0)
    await page.getByText('＋ 记录一次成长', { exact: true }).click()
    await page.screenshot({ path: path.join(artifacts, 'record-form.png') })
    await page.getByLabel('身高或身长，单位厘米', { exact: true }).fill('108.2')
    await page.getByLabel('体重，单位千克', { exact: true }).fill('18.1')
    await page.getByRole('button', { name: '身高增加0.1厘米', exact: true }).click()
    assert.equal(await page.getByLabel('身高或身长，单位厘米', { exact: true }).inputValue(), '108.3')
    await page.evaluate(() => { window.failSave = true })
    await page.getByRole('button', { name: '保存这次成长', exact: true }).click()
    await page.getByText('网络暂不可用，内容已保留', { exact: true }).waitFor()
    assert.equal(await page.getByLabel('体重，单位千克', { exact: true }).inputValue(), '18.1')
    await page.getByRole('button', { name: '保存这次成长', exact: true }).click()
    await page.locator('.growth-sheet').waitFor({ state: 'detached' })
    assert.equal(await page.evaluate(() => window.page.data.records.length), 6)
    verified.push('decimal input, steppers, failure preserves draft, successful save')
    await page.locator('.timeline-entry').first().click()
    await page.getByRole('button', { name: '删除这次记录', exact: true }).click()
    await page.locator('.growth-sheet').waitFor({ state: 'detached' })
    assert.equal(await page.evaluate(() => window.page.data.records.length), 5)
    verified.push('edit and confirmed delete')
    for (const width of [320, 375, 430]) {
      await page.setViewportSize({ width, height: 740 })
      await page.evaluate(() => document.querySelector('.growth-scroll').scrollTop = 0)
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `overflow at ${width}`)
      await page.getByText('＋ 记录一次成长', { exact: true }).click()
      await page.getByLabel('身高或身长，单位厘米', { exact: true }).fill('109')
      await page.getByLabel('体重，单位千克', { exact: true }).fill('19')
      const box = await page.locator('.growth-sheet').boundingBox()
      assert.ok(box.x >= -1 && box.x + box.width <= width + 1)
      await page.getByRole('button', { name: '关闭', exact: true }).click()
      await page.locator('.growth-sheet').waitFor({ state: 'detached' })
    }
    verified.push('320/375/430px layout and draft dismissal')
    await page.setViewportSize({ width: 390, height: 500 })
    await page.getByText('＋ 记录一次成长', { exact: true }).click()
    await page.getByRole('button', { name: '保存这次成长', exact: true }).scrollIntoViewIfNeeded()
    assert.ok(await page.getByRole('button', { name: '保存这次成长', exact: true }).isVisible())
    await page.getByRole('button', { name: '关闭', exact: true }).click()
    await page.setViewportSize({ width: 390, height: 844 })
    await page.getByRole('button', { name: '参考说明 ⓘ', exact: true }).click()
    await page.getByText('读懂这片参考色带', { exact: true }).waitFor()
    await page.getByRole('button', { name: '复制 CDC 官方数据网址', exact: true }).click()
    assert.match(await page.evaluate(() => window.copied), /cdc.gov/)
    await page.getByRole('button', { name: '关闭', exact: true }).click()
    verified.push('short viewport sheet scrolling and reference source')
    await page.evaluate(() => { window.page.setData({ profiles: [], activeChild: null, error: '', loading: false }); window.page.onAddChild() })
    await page.getByLabel('孩子的昵称', { exact: true }).fill('小朋友')
    await page.locator('input[type="date"][aria-label="选择出生日期"]').fill('2025-08-20')
    await page.getByRole('button', { name: '女孩', exact: true }).click()
    await page.getByRole('button', { name: '保存孩子档案', exact: true }).click()
    await page.getByText('小朋友的成长手记', { exact: true }).waitFor()
    assert.equal(await page.evaluate(() => window.page.data.activeChild.sex), 'girl')
    verified.push('new multi-child profile and empty timeline')
    await page.evaluate(() => { window.failNext = true; window.page.refresh() })
    await page.getByRole('button', { name: '重新读取', exact: true }).waitFor()
    await page.getByRole('button', { name: '重新读取', exact: true }).click()
    await page.getByText('小朋友的成长手记', { exact: true }).waitFor()
    verified.push('read failure and retry')
    assert.deepEqual(errors, [])
    fs.writeFileSync(path.join(artifacts, 'browser-evidence.json'), JSON.stringify({ adapter: 'actual WXML/WXSS + page handlers, mocked platform/cloud APIs', verified, errors }, null, 2))
    console.log(`Passed ${verified.length} browser workflow checks; evidence: ${artifacts}`)
  } finally { if (browser) await browser.close(); await new Promise(resolve => server.close(resolve)) }
}
main().catch(err => { console.error(err); process.exit(1) })
