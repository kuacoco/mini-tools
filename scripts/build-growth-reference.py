"""Build P3/P50/P97 reference knots from the unmodified CDC 2000 CSVs."""
import csv
import hashlib
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
output = {'source': 'CDC 2000', 'url': 'https://www.cdc.gov/growthcharts/cdc-data-files.htm', 'series': {}}
for filename, key in [('lenageinf', 'length'), ('wtageinf', 'infantWeight'), ('statage', 'height'), ('wtage', 'weight')]:
    file = ROOT / 'data/growth/source' / (filename + '.csv')
    rows = list(csv.DictReader(file.read_text(encoding='utf-8-sig').splitlines()))
    output['series'][key] = {}
    for code, sex in [('1', 'boy'), ('2', 'girl')]:
        # Retain the first knot beyond 18 years for boundary interpolation.
        values = [[float(row[c]) for c in ['Agemos', 'P3', 'P50', 'P97']] for row in rows if row['Sex'].strip() == code and float(row['Agemos']) <= 216.5]
        assert values and all(a[0] < b[0] for a, b in zip(values, values[1:]))
        assert all(r[1] < r[2] < r[3] for r in values)
        output['series'][key][sex] = values
    print(filename, hashlib.sha256(file.read_bytes()).hexdigest())
(ROOT / 'utils/growth-reference.js').write_text('// Generated by scripts/build-growth-reference.py; do not edit by hand.\nmodule.exports = ' + json.dumps(output, separators=(',', ':')) + '\n')
